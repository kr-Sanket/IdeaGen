"""Automated Unit and Safeguard Tests for Stage 4D Independent Classifier Evaluation.

Verifies:
1. The evaluation runner never derives predictions from gold labels.
2. A classifier prediction different from the gold label produces the correct confusion-matrix entry.
3. Provider failures and malformed outputs are recorded as failures/abstentions rather than silently replaced with gold labels.
4. Split and source-category metrics partition cases strictly and correctly.
5. A no-provider environment cannot accidentally emit a fabricated accuracy score.
"""

from __future__ import annotations

import pytest
from unittest.mock import MagicMock

from ideagen.opportunity.models import OpportunityRelationship, OpportunityStatus
from ideagen.opportunity.classifier import (
    RelationshipClassifier,
    RelationshipClassificationInput,
    RelationshipClassification,
)
from ideagen.llm.provider import LLMProvider
from ideagen.llm.exceptions import ProviderFailureError, MalformedResponseError
from ideagen.evaluation.stage4b_benchmark import (
    Stage4bBenchmarkCase,
    BenchmarkSplit,
    CaseSourceCategory,
    GroundingChallengeType,
    get_stage4b_benchmark_dataset,
)
from ideagen.evaluation.stage4d_evaluator import (
    IndependentClassifierEvaluator,
    EvaluationPredictionStatus,
    build_isolated_classifier_input,
    compute_contingency_and_metrics,
)


class DummyMockProvider(LLMProvider):
    def __init__(self, fixed_relationship: OpportunityRelationship = OpportunityRelationship.ADDRESSES):
        self.fixed_relationship = fixed_relationship
        self._calls = 0

    @property
    def model_name(self) -> str:
        return "dummy-eval-mock:v1"

    def generate_structured(self, prompt: str, response_schema):
        self._calls += 1
        return RelationshipClassification(
            relationship=self.fixed_relationship,
            confidence=0.85,
            rationale="Dummy mock rationale for testing metrics pipeline.",
            evidence_excerpt="Sample mock excerpt",
        )


class FlakyErrorProvider(LLMProvider):
    def __init__(self):
        self._call_count = 0

    @property
    def model_name(self) -> str:
        return "flaky-error-provider:v1"

    def generate_structured(self, prompt: str, response_schema):
        self._call_count += 1
        if self._call_count == 1:
            raise ProviderFailureError("Simulated LLM connection timeout.")
        elif self._call_count == 2:
            raise MalformedResponseError("Simulated invalid JSON from LLM.")
        return RelationshipClassification(
            relationship=OpportunityRelationship.SUPPORTS,
            confidence=0.90,
            rationale="Success rationale after errors.",
            evidence_excerpt="Valid excerpt",
        )


def test_runner_never_derives_predictions_from_gold_labels():
    """Requirement 1: Input to RelationshipClassifier contains zero knowledge of expected_relationship."""
    cases = get_stage4b_benchmark_dataset()
    case_0 = cases[0]

    input_payload = build_isolated_classifier_input(case_0)

    # Verify input payload fields
    assert not hasattr(input_payload, "expected_relationship")
    assert not hasattr(input_payload, "gold_relationship")
    assert not hasattr(input_payload, "expected_grounding_valid")

    # Verify prompt string built by classifier does not contain the gold label name
    mock_provider = DummyMockProvider(OpportunityRelationship.ADDRESSES)
    classifier = RelationshipClassifier(provider=mock_provider)

    evaluator = IndependentClassifierEvaluator(classifier=classifier, benchmark_cases=[case_0])
    report = evaluator.evaluate()

    assert len(report.records) == 1
    rec = report.records[0]
    # The gold relationship is case_0.expected_relationship (ADDRESSES), but prediction was generated by mock
    assert rec.predicted_relationship == OpportunityRelationship.ADDRESSES
    assert rec.prediction_status == EvaluationPredictionStatus.SUCCESS


def test_classifier_prediction_different_from_gold_produces_correct_matrix_entry():
    """Requirement 2: Classifier returning non-gold label updates the off-diagonal cell accurately."""
    cases = get_stage4b_benchmark_dataset()
    # Case DEV-02 has gold_relationship = SUPPORTS
    case_dev02 = next(c for c in cases if c.case_id == "DEV-02")
    assert case_dev02.expected_relationship == OpportunityRelationship.SUPPORTS

    # Configure mock classifier to return ADDRESSES instead of SUPPORTS
    mock_provider = DummyMockProvider(fixed_relationship=OpportunityRelationship.ADDRESSES)
    classifier = RelationshipClassifier(provider=mock_provider)

    evaluator = IndependentClassifierEvaluator(classifier=classifier, benchmark_cases=[case_dev02])
    report = evaluator.evaluate()

    rec = report.records[0]
    assert rec.gold_relationship == OpportunityRelationship.SUPPORTS
    assert rec.predicted_relationship == OpportunityRelationship.ADDRESSES

    # Verify confusion matrix entry
    dev_metrics = report.metrics_by_split["DEV"]
    matrix = dev_metrics["confusion_matrix"]
    # Row: SUPPORTS (true), Column: ADDRESSES (pred)
    assert matrix["SUPPORTS"]["ADDRESSES"] == 1
    assert matrix["SUPPORTS"]["SUPPORTS"] == 0
    assert dev_metrics["overall_accuracy"] == 0.0


def test_provider_failures_and_malformed_outputs_recorded_as_abstentions():
    """Requirement 3: Provider errors and malformed responses are captured as failures, never replaced by gold labels."""
    cases = get_stage4b_benchmark_dataset()[:3]  # 3 test cases
    flaky_provider = FlakyErrorProvider()
    classifier = RelationshipClassifier(provider=flaky_provider)

    evaluator = IndependentClassifierEvaluator(classifier=classifier, benchmark_cases=cases)
    report = evaluator.evaluate()

    assert report.total_cases == 3
    assert report.successful_predictions == 1
    assert report.failed_predictions == 2

    # Case 0 failed with ProviderFailureError
    rec_0 = report.records[0]
    assert rec_0.prediction_status == EvaluationPredictionStatus.PROVIDER_FAILURE
    assert rec_0.predicted_relationship is None
    assert "Simulated LLM connection timeout" in str(rec_0.error_message)

    # Case 1 failed with MalformedResponseError
    rec_1 = report.records[1]
    assert rec_1.prediction_status == EvaluationPredictionStatus.MALFORMED_OUTPUT
    assert rec_1.predicted_relationship is None
    assert "Simulated invalid JSON" in str(rec_1.error_message)

    # Case 2 succeeded
    rec_2 = report.records[2]
    assert rec_2.prediction_status == EvaluationPredictionStatus.SUCCESS
    assert rec_2.predicted_relationship == OpportunityRelationship.SUPPORTS

    # Verify failure breakdown dict
    assert report.failure_breakdown["PROVIDER_FAILURE"] == 1
    assert report.failure_breakdown["MALFORMED_OUTPUT"] == 1


def test_split_and_source_category_metrics_partition_correctly():
    """Requirement 4: Split and category metrics strictly isolate their respective case sets."""
    cases = get_stage4b_benchmark_dataset()
    mock_provider = DummyMockProvider(OpportunityRelationship.ADDRESSES)
    classifier = RelationshipClassifier(provider=mock_provider)

    evaluator = IndependentClassifierEvaluator(classifier=classifier, benchmark_cases=cases)
    report = evaluator.evaluate()

    # DEV split has 10 cases, HELD_OUT has 15 cases
    assert report.metrics_by_split["DEV"]["evaluated_count"] == 10
    assert report.metrics_by_split["HELD_OUT"]["evaluated_count"] == 15

    # Categories
    assert report.metrics_by_category["REAL_LITERATURE"]["evaluated_count"] == 11
    assert report.metrics_by_category["HUMAN_CURATED_PILOT"]["evaluated_count"] == 13
    assert report.metrics_by_category["SYNTHETIC_STRESS_TEST"]["evaluated_count"] == 1


def test_no_provider_environment_cannot_emit_fabricated_accuracy():
    """Requirement 5: Running without a classifier provider refuses to fabricate accuracy."""
    cases = get_stage4b_benchmark_dataset()

    evaluator = IndependentClassifierEvaluator(classifier=None, benchmark_cases=cases)
    report = evaluator.evaluate()

    assert report.is_empirical_inference is False
    assert report.llm_provider is None
    assert report.model_name is None
    assert report.empirical_accuracy is None  # Must NOT be a float or fabricated percentage
    assert report.successful_predictions == 0
    assert report.failed_predictions == 25
    assert report.failure_breakdown["NO_PROVIDER"] == 25

    for rec in report.records:
        assert rec.prediction_status == EvaluationPredictionStatus.NO_PROVIDER
        assert rec.predicted_relationship is None
        assert "No LLM provider available" in str(rec.error_message)
